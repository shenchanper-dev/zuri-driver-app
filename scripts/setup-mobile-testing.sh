#!/bin/bash

# ============================================================================
# ZURI Driver App - Script de Setup para Pruebas Móviles
# ============================================================================
# Este script automatiza la configuración para probar la app desde celular
# ============================================================================

set -e

echo "🚗 ZURI Driver App - Setup para Pruebas Móviles"
echo "================================================"
echo ""

# Colores
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m' # No Color

# ============================================================================
# 1. Obtener IP local
# ============================================================================
echo -e "${YELLOW}📡 Detectando IP local...${NC}"
IP_ADDRESS=$(hostname -I | awk '{print $1}')

if [ -z "$IP_ADDRESS" ]; then
    echo -e "${RED}❌ No se pudo detectar la IP local${NC}"
    exit 1
fi

echo -e "${GREEN}✅ IP detectada: $IP_ADDRESS${NC}"
echo ""

# ============================================================================
# 2. Crear archivo .env con la IP correcta
# ============================================================================
echo -e "${YELLOW}📝 Configurando archivo .env...${NC}"

cat > .env << EOF
# API Configuration for Mobile Testing
# Auto-generated by setup-mobile-testing.sh
EXPO_PUBLIC_API_URL=http://$IP_ADDRESS:3000/api
EXPO_PUBLIC_SOCKET_URL=ws://$IP_ADDRESS:3001

# For production, use:
# EXPO_PUBLIC_API_URL=https://admin.zuri.pe/api
# EXPO_PUBLIC_SOCKET_URL=wss://admin.zuri.pe
EOF

echo -e "${GREEN}✅ Archivo .env actualizado${NC}"
echo ""
cat .env
echo ""

# ============================================================================
# 3. Verificar que los servicios estén corriendo
# ============================================================================
echo -e "${YELLOW}🔍 Verificando servicios backend...${NC}"

# Verificar Next.js (puerto 3000)
if curl -s http://localhost:3000 > /dev/null; then
    echo -e "${GREEN}✅ Next.js corriendo en puerto 3000${NC}"
else
    echo -e "${RED}❌ Next.js NO está corriendo en puerto 3000${NC}"
    echo -e "${YELLOW}   Inicia el backend con: cd ~/zuri-platform && npm run dev${NC}"
fi

# Verificar WebSocket (puerto 3001)
if lsof -i:3001 > /dev/null 2>&1; then
    echo -e "${GREEN}✅ WebSocket corriendo en puerto 3001${NC}"
else
    echo -e "${RED}❌ WebSocket NO está corriendo en puerto 3001${NC}"
    echo -e "${YELLOW}   Inicia WebSocket con: cd ~/zuri-platform && npx tsx src/server/websocket.ts${NC}"
fi

echo ""

# ============================================================================
# 4. Verificar conductor Max en la BD
# ============================================================================
echo -e "${YELLOW}👤 Verificando conductor Max Beltran...${NC}"

PSQL_OUTPUT=$(psql -U postgres -d zuri_db -t -c "SELECT id, nombres, apellidos, estado FROM conductores WHERE dni = '08466466';" 2>/dev/null || echo "")

if [ -z "$PSQL_OUTPUT" ]; then
    echo -e "${RED}❌ No se pudo conectar a PostgreSQL o conductor no existe${NC}"
    echo -e "${YELLOW}   Verifica que PostgreSQL esté corriendo${NC}"
else
    echo -e "${GREEN}✅ Conductor encontrado:${NC}"
    echo "$PSQL_OUTPUT"
fi

echo ""

# ============================================================================
# 5. Instrucciones finales
# ============================================================================
echo -e "${GREEN}================================================${NC}"
echo -e "${GREEN}✅ Setup completado${NC}"
echo -e "${GREEN}================================================${NC}"
echo ""
echo -e "${YELLOW}📱 Próximos pasos:${NC}"
echo ""
echo "1. Inicia Expo:"
echo -e "   ${GREEN}npm start${NC}"
echo ""
echo "2. Escanea el QR con Expo Go desde tu celular"
echo ""
echo "3. Login con:"
echo -e "   DNI: ${GREEN}08466466${NC}"
echo -e "   PIN: ${YELLOW}(Si es primera vez, sigue el flujo de registro)${NC}"
echo ""
echo "4. Monitorea los logs del backend para obtener el código SMS"
echo ""
echo -e "${YELLOW}📝 URLs configuradas:${NC}"
echo -e "   API:       ${GREEN}http://$IP_ADDRESS:3000/api${NC}"
echo -e "   WebSocket: ${GREEN}ws://$IP_ADDRESS:3001${NC}"
echo ""
echo -e "${YELLOW}🌐 Asegúrate de que tu celular esté en la misma red WiFi${NC}"
echo ""
